F = 1 / 144            # panel px (1920 wide) -> inches
INK, BROWN, DBROWN, GREEN, DGREEN, SKY, GOLD, RED, CREAM = '#3B2A1E', '#8D5A3B', '#5D3A22', '#4E8A3A', '#2F6B2A', '#2F7FB0', '#F5A623', '#C0392B', '#FFF8EC'
D = Deck()


def px(s, x, y, w, h, paras, size, color=INK, fill=None, line=None, **kw):
    return tbox(s, x * F, y * F, w * F, h * F, paras, size, color, fill, line, **kw)


def sig(s):
    tbox(s, .15, 7.02, 2.1, .38, 'أ/ شامه البقمي', 13, DBROWN, CREAM, '#D9C3A0', align='c', radius=.5, lw=1.5, margin=.03)


def star(s, x, y, size=.55):
    return tbox(s, x, y, size, size * .92, '', 10, fill='#FFD54F', line=GOLD, shape='star')


def vis(name, note, page=None):
    s = D.slide(V(name), 'fade')
    sig(s)
    if page:
        tbox(s, 11.0, 7.02, 2.2, .38, page, 13, '#FFFFFF', SKY, align='c', radius=.5, margin=.03)
    notes(s, note)
    return s


def reveal(s, trig, *targets, sound='chime'):
    trigger_steps(s, trig, tuple([[targets[0], 'zoom', S(s, sound)]] + [[t, 'zoom'] for t in targets[1:]]))


def answer(s, x, y, w, h, text, size=18, label='الإجابة: '):
    return tbox(s, x, y, w, h, [[(label, '#FFF59D'), (text, '#FFFFFF')]], size, '#FFFFFF', DGREEN, '#FFFFFF', lw=2.5, radius=.25)


def qa(s, x, y, w, q, a, qh=.75, ah=.75, qsize=19, asize=17, label='الإجابة: '):
    qb = tbox(s, x, y, w, qh, q, qsize, INK, '#FFFFFF', RED, lw=3, radius=.25)
    ab = answer(s, x, y + qh + .08, w, ah, a, asize, label)
    reveal(s, qb, ab, star(s, x - .2, y + qh - .3, .5))
    return qb


def bookslide(title, page_name, page_label, note):
    s = D.slide(f'{ROOT}/art/bg.jpg', 'push')
    tbox(s, 3.2, .2, 6.9, .85, title, 30, '#FFFFFF', BROWN, '#FFFFFF', align='c', lw=3, radius=.4)
    p = pic(s, BK(page_name), 8.15, 1.3, h=5.55, border='#FFFFFF')
    p.line.color.rgb = rgb(BROWN); p.line.width = Pt(3)
    tbox(s, 8.15, 6.9, p.width / 914400, .42, 'من كتابي – ' + page_label, 14, '#FFFFFF', SKY, align='c', radius=.5, margin=.02)
    sig(s)
    notes(s, note)
    return s


