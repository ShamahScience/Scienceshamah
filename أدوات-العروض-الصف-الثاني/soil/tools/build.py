def reveal(s, trig, *targets, sound='chime'):
    trigger_steps(s, trig, tuple([[targets[0], 'zoom', S(s, sound)]] + [[t, 'zoom'] for t in targets[1:]]))


def answer(s, x, y, w, h, text, size=18, label='الإجابة: '):
    return tbox(s, x, y, w, h, [[(label, '#FFF59D'), (text, '#FFFFFF')]], size, '#FFFFFF', DGREEN, '#FFFFFF', lw=2.5, radius=.25)


def qa(s, x, y, w, q, a, qh=.75, ah=.75, qsize=19, asize=17, label='الإجابة: '):
    qb = tbox(s, x, y, w, qh, q, qsize, INK, '#FFFFFF', RED, lw=3, radius=.25)
    ab = answer(s, x, y + qh + .08, w, ah, a, asize, label)
    reveal(s, qb, ab, star(s, x - .2, y + qh - .3, .5))
    return qb


def hl(text, words, base=INK, mark=RED):
    runs, rest = [], text
    while rest:
        hits = [(rest.find(w), w) for w in words if rest.find(w) >= 0]
        if not hits:
            runs.append((rest, base)); break
        i, w = min(hits)
        if i: runs.append((rest[:i], base))
        runs.append((w, mark)); rest = rest[i + len(w):]
    return [runs]


def guided(title, page_name, label, before, sents, after_q, after_a, note, name=None):
    """Guided reading: a purpose before reading, the book text sentence by sentence with key words, then a question after reading."""
    s = bookslide(title, page_name, label, note)
    if name: s._name = name
    tbox(s, .4, 1.15, 7.5, .78, [[('📖 قَبْلَ الْقِرَاءَةِ: ', '#8E44AD'), (before, INK)]], 18, fill='#F3E5F5', line='#CE93D8', lw=2.5, radius=.3)
    y = 2.05; boxes = []
    for txt, words, h in sents:
        boxes.append(tbox(s, .4, y, 7.5, h, hl(txt, words), 17, INK, '#FFFFFF', BROWN, lw=2.5, radius=.2)); y += h + .1
    click(s, *[[b, 'rise', S(s, 'pop')] for b in boxes])
    qa(s, .4, y + .05, 7.5, '✔ بَعْدَ الْقِرَاءَةِ: ' + after_q, after_a, qh=.6, ah=1.0, qsize=17, asize=14)
    return s



