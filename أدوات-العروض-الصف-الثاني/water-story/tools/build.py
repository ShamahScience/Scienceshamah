def star(s, x, y, size=.55):
    return tbox(s, x, y, size, size * .92, '', 10, fill='#FFD54F', line=GOLD, shape='star')


def reveal(s, q, *targets, sound='chime'):
    t = list(targets)
    trigger_steps(s, q, tuple([[t[0], 'zoom', S(s, sound)]] + [[x, 'zoom'] for x in t[1:]]))


def qa(s, x, y, w, q, a, qh=.85, ah=.85, qsize=18, asize=16, label='الإجابة: ', qline=RED):
    qb = card(s, x, y, w, qh, q, qsize, line=qline, lw=3)
    ab = answer(s, x, y + qh + .08, w, ah, [[(label, '#FFF59D'), (a, '#FFFFFF')]], asize)
    st = star(s, x - .2, y + qh - .25, .5)
    reveal(s, qb, ab, st)
    return qb


def option(s, x, y, w, h, text, ok, size=18, line=GOLD, fill='#FFFFFF'):
    b = tbox(s, x, y, w, h, text, size, INK, fill, line, align='c', lw=3, margin=.04)
    if ok:
        m = tbox(s, x + w - .32, y - .22, .55, .55, '✔', 18, '#FFFFFF', GREEN, '#FFFFFF', shape='oval', align='c', margin=0)
        st = star(s, x - .25, y - .25, .55)
        trigger_steps(s, b, ([m, 'zoom', S(s, 'chime')], [st, 'zoom', S(s, 'sparkle')]))
    else:
        m = tbox(s, x + w - .32, y - .22, .55, .55, '✘', 18, '#FFFFFF', '#D23B3B', '#FFFFFF', shape='oval', align='c', margin=0)
        trigger_steps(s, b, ([m, 'zoom', S(s, 'wrong')],))
    return b


def hl(text, words, base=INK, mark=PINK):
    runs, rest = [], text
    while rest:
        hits = [(rest.find(w), w) for w in words if rest.find(w) >= 0]
        if not hits:
            runs.append((rest, base)); break
        i, w = min(hits)
        if i: runs.append((rest[:i], base))
        runs.append((w, mark)); rest = rest[i + len(w):]
    return [runs]



