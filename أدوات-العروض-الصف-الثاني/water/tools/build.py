def note(s, txt):
    notes(s, txt + '\n' + getattr(s, '_strategy', ''))


def say(s, text, size=14):
    """The girl in the background speaks: a bubble above her head."""
    b = tbox(s, .15, .12, 2.85, 1.0, [[(text, NAVY, size)]], size, fill='#FFFFFF', line=ROSE, shape='bubble', lw=2.5, margin=.06, align='c')
    b.adjustments[0], b.adjustments[1] = -.1, .78
    return b


def drop(s, x, y, h=1.25, text=None, size=13, bw=2.2):
    p = pic(s, f'{ROOT}/art/drop.png', x, y, h=h)
    if text:
        b = tbox(s, x - bw + .25, y - .95, bw, .85, [[(text, '#0D47A1', size)]], size, fill='#FFFFFF', line='#64B5F6', shape='bubble', lw=2.5, margin=.05, align='c')
        b.adjustments[0], b.adjustments[1] = .3, .75
    return p


def ist(s, x, y, size=.55):
    return tbox(s, x, y, size, size * .92, '', 10, fill='#FFD54F', line=GOLD, shape='star')


def option(s, x, y, w, h, text, ok, size=18, fill='#FFFFFF', line='#90CAF9'):
    b = tbox(s, x, y, w, h, text, size, NAVY, fill, line, align='c', lw=3, margin=.03, radius=.5)
    if ok:
        m = tbox(s, x + w - .3, y - .22, .5, .5, '✔', 16, '#FFFFFF', GREEN, '#FFFFFF', shape='oval', align='c', margin=0)
        st = ist(s, x - .22, y - .24, .5)
        trigger_steps(s, b, ([m, 'zoom', S(s, 'chime')], [st, 'zoom', S(s, 'sparkle')]))
    else:
        m = tbox(s, x + w - .3, y - .22, .5, .5, '✘', 16, '#FFFFFF', '#D23B3B', '#FFFFFF', shape='oval', align='c', margin=0)
        trigger_steps(s, b, ([m, 'zoom', S(s, 'wrong')],))
    return b


def ask_reveal(s, qbox, ans, sound='chime'):
    trigger_steps(s, qbox, ([ans, 'zoom', S(s, sound)],))


def hl(text, words, base=NAVY, mark='#C2185B'):
    runs, rest = [], text
    while rest:
        hits = [(rest.find(w), w) for w in words if rest.find(w) >= 0]
        if not hits:
            runs.append((rest, base)); break
        i, w = min(hits)
        if i: runs.append((rest[:i], base))
        runs.append((w, mark)); rest = rest[i + len(w):]
    return [runs]


def bookthumb(s, name, x, y, w=None, h=None, cap=None):
    p = pic(s, BK(name), x, y, w, h, border='#FFFFFF')
    if cap:
        tbox(s, x, y + p.height / 914400 - .05, p.width / 914400, .34, cap, 12, '#FFFFFF', '#F39C12', align='c', radius=.5, margin=.02)
    return p


