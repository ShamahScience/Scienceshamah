def star(s, x, y, size=.55):
    return tbox(s, x, y, size, size * .92, '', 10, fill='#FFD54F', line=GOLD, shape='star')


def qa(s, x, y, w, q, a, qh=.7, ah=.7, qsize=18, asize=16, label='الإجابة: ', qfill='#FFFFFF', qline=BLUE):
    """The book's question; clicking it shows the green answer bar, a star and a chime."""
    qb = tbox(s, x, y, w, qh, q, qsize, NAVY, qfill, qline, lw=2.5, radius=.3)
    ab = tbox(s, x + .3, y + qh + .08, w - .3, ah, [[(label, '#FFF59D', asize), (a, '#FFFFFF', asize)]], asize, fill=GREEN, line='#FFFFFF', lw=2, radius=.3)
